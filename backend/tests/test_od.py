"""起讫站（OD）解析测试。

槽位抽取常把区间放进 `direction`（如"北京到上海"），
本测试确保这些口语化表述都能解析成 (出发站, 到达站)。
"""
from __future__ import annotations

from app.od import parse_od


def main():
    cases = [
        ("北京到上海", ("北京", "上海")),
        ("北京至上海", ("北京", "上海")),
        ("北京→上海", ("北京", "上海")),
        ("北京->上海", ("北京", "上海")),
        ("北京-上海", ("北京", "上海")),
        ("从北京去上海", ("北京", "上海")),
        ("北京去上海", ("北京", "上海")),
        ("上海虹桥至北京南", ("上海虹桥", "北京南")),
        ("北京到上海高铁", ("北京", "上海")),
        # ---- R1 缺陷 P0-3 回归：口语化问句（句末问号/追问短语/句首时间词）----
        ("北京到上海走哪条线路？", ("北京", "上海")),
        ("明天北京到上海还有票吗？", ("北京", "上海")),
        ("从北京去上海怎么走", ("北京", "上海")),
        ("后天上海虹桥至北京南", ("上海虹桥", "北京南")),
        # 同站对如实返回（F07：交给 rail.line 给出"发站与到站相同"）
        ("北京到北京", ("北京", "北京")),
    ]
    for raw, expected in cases:
        got = parse_od(raw)
        assert got == expected, f"parse_od({raw!r}) = {got!r}, 期望 {expected!r}"
        print(f"[PASS] parse_od({raw!r}) -> {got}")

    # 非区间表述应返回 None
    for raw in ("上行", "下行", "北京", "", None, "哈尔滨方向",
                # 时间/时段表述不能当站名（D09 回归：曾把"明天下午"当成出发站）
                "明天下午到上海的高铁都有几点的？", "1461 都经过哪些站？"):
        got = parse_od(raw)
        assert got is None, f"parse_od({raw!r}) 应为 None，实际 {got!r}"
        print(f"[PASS] parse_od({raw!r}) -> None")

    test_guided_parsing()
    test_no_validator_keeps_rules_only()

    print("\nOD 解析测试全部通过 ✔")


# 引导式解析用的小词表（**注入式**，不依赖站点库 → 本套件保持无网络、可离线跑）
_FAKE_STATIONS = frozenset({
    "北京", "上海", "北京南", "上海虹桥", "深圳北", "厦门北",
    "南京", "南京南", "杭州东", "西安", "兰州", "济南西", "广州",
})


def test_guided_parsing():
    """注入"这是不是站名"的谓词后，原来解不出/解错的区间问法全部正确。

    改前实测：单轮含区间的语料 18 条里 **7 条错/漏**（都用的是极自然的说法）：
      · 解不出：`深圳北到厦门北今天还有票吗？要高铁的`（目的地超 10 字上限且夹问号）
               `北京南到上海虹桥的高铁全程几个小时`
      · 解错：  `有没有通宵的车从西安到兰州` → ('有没有通宵的车从西安','兰州')
               `从北京坐到上海走的是哪条线？` → ('北京坐','上海走')
    根因是"整串匹配 + 只剥句末词"：一串杂词卡在目的地里就整串不匹配，而起点侧
    刻意不切停用词（克制是对的——「成都东」里有"都"），于是杂词留在起点。
    引导式解析改为"站点库消歧、规则只负责切候选"，从两端向内收缩到真实站名。
    """
    ok = _FAKE_STATIONS.__contains__
    cases = [
        # 原有能力不能退化
        ("北京到上海", ("北京", "上海")),
        ("上海虹桥至北京南", ("上海虹桥", "北京南")),
        ("从北京去上海怎么走", ("北京", "上海")),
        ("明天北京到上海还有票吗？", ("北京", "上海")),
        ("北京到北京", ("北京", "北京")),
        # 目的地夹杂词/超长 → 改前解不出
        ("深圳北到厦门北今天还有票吗？要高铁的", ("深圳北", "厦门北")),
        ("北京南到上海虹桥的高铁全程几个小时", ("北京南", "上海虹桥")),
        ("南京南到杭州东这段大概要跑多久", ("南京南", "杭州东")),
        ("从南京到上海的普速车走京沪线还是别的线", ("南京", "上海")),
        # 起点夹杂词 → 改前解出垃圾
        ("有没有通宵的车从西安到兰州", ("西安", "兰州")),
        ("北京到上海为什么不放票", ("北京", "上海")),
        ("从北京坐到上海走的是哪条线？", ("北京", "上海")),
    ]
    for raw, expected in cases:
        got = parse_od(raw, station_ok=ok)
        assert got == expected, f"parse_od({raw!r}, station_ok=…) = {got!r}, 期望 {expected!r}"
    print(f"[PASS] 引导式解析：{len(cases)} 条（含 7 条改前失败的）全部正确")

    # 红线：时间/时段表述仍然不算站名（引导式也不许把它们当起点）
    for raw in ("明天下午到上海的高铁都有几点的？", "今天到北京"):
        got = parse_od(raw, station_ok=ok)
        assert got is None or _FAKE_STATIONS.issuperset(got), f"{raw!r} -> {got!r}"
    print("[PASS] 引导式解析仍不把时间表述当站名")


def test_no_validator_keeps_rules_only():
    """不给谓词（或站点库不可用）时，行为必须与旧实现**逐字一致**。

    为什么要钉：`app/od.py` 是纯字符串工具，被大量无网络单测/脚本直接调用；
    改动只应在"能拿到站点库"时生效，否则就是悄悄换了所有人的解析口径。
    """
    # station_ok 明确传 None 时是否启用默认谓词取决于环境，这里直接传一个"全是假"的谓词，
    # 等价于"站点库不可用"。
    deny = (lambda _n: False)
    # 旧路径解不出来的，仍然解不出来（不会因为"有谓词"就硬凑）
    assert parse_od("深圳北到厦门北今天还有票吗？要高铁的", station_ok=deny) is None
    # 旧路径解出来的（含垃圾），原样返回 —— 说明兜底没有改变旧行为
    assert parse_od("北京到上海", station_ok=deny) == ("北京", "上海")
    assert parse_od("从北京坐到上海走的是哪条线？", station_ok=deny) == ("北京坐", "上海走")
    print("[PASS] 无可用站点库时退回纯规则解析（旧行为逐字一致）")


if __name__ == "__main__":
    main()